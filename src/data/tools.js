export const sortTools = (toolsList, sortBy) => {
  switch (sortBy) {
    case "popular":
      return [...toolsList].sort((a, b) => (b.popular ? 1 : 0) - (a.popular ? 1 : 0));
    case "newest":
      return [...toolsList].sort((a, b) => (b.isNew ? 1 : 0) - (a.isNew ? 1 : 0));
    case "rating":
      return [...toolsList].sort((a, b) => b.rating - a.rating);
    case "name":
      return [...toolsList].sort((a, b) => a.name.localeCompare(b.name));
    default:
      return toolsList;
  }
};